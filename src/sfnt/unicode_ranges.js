export function computeUnicodeRangeBits(unicodeSet) {
	const points = [...unicodeSet].sort((a, b) => a - b);
	if (points.some((point) => !Number.isInteger(point) || point < 0 || point > 0x10ffff ||
		(point >= 0xd800 && point <= 0xdfff)))
		throw new Error('Unicode range derivation requires scalar values.');
	const words = [0, 0, 0, 0];
	for (const [bit, start, end] of ranges) {
		let low = 0, high = points.length;
		while (low < high) {
			const middle = Math.floor((low + high) / 2);
			if (points[middle] < start) low = middle + 1;
			else high = middle;
		}
		if (low < points.length && points[low] <= end)
			words[bit >>> 5] = (words[bit >>> 5] | (1 << (bit & 31))) >>> 0;
	}
	return words;
}
